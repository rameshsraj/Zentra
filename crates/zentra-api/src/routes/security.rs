use axum::{Router, routing::{get, post, put, delete}};
use crate::state::AppState;
use crate::handlers;

pub fn router() -> Router<AppState> {
    Router::new()
        // IDS/IPS (V5 Prompt 6)
        .route("/api/security/ids/rules", get(handlers::ids_ips::list_rules))
        .route("/api/security/ids/rules", post(handlers::ids_ips::create_rule))
        .route("/api/security/ids/rules/bulk", post(handlers::ids_ips::bulk_rules))
        .route("/api/security/ids/rules/import", post(handlers::ids_ips::import_rules))
        .route("/api/security/ids/rules/:id", put(handlers::ids_ips::update_rule))
        .route("/api/security/ids/rules/:id", delete(handlers::ids_ips::delete_rule))
        .route("/api/security/ids/alerts", get(handlers::ids_ips::list_alerts))
        .route("/api/security/ids/alerts/:id", get(handlers::ids_ips::get_alert))
        .route("/api/security/ids/alerts/:id/status", put(handlers::ids_ips::update_alert_status))
        .route("/api/security/ids/stats", get(handlers::ids_ips::ids_stats))
        .route("/api/security/ids/ingest", post(handlers::ids_ips::ingest_eve))

        // Network Security — Traffic Analysis (V5 Prompt 7)
        .route("/api/security/connections", get(handlers::network_security::list_connections))
        .route("/api/security/connections/stats", get(handlers::network_security::connection_stats))
        .route("/api/security/connections/:id", get(handlers::network_security::get_connection))
        .route("/api/security/dns", get(handlers::network_security::list_dns))
        .route("/api/security/dns/stats", get(handlers::network_security::dns_stats))
        .route("/api/security/http", get(handlers::network_security::list_http))
        .route("/api/security/http/stats", get(handlers::network_security::http_stats))
        .route("/api/security/ssl", get(handlers::network_security::list_ssl))
        .route("/api/security/ssl/stats", get(handlers::network_security::ssl_stats))
        .route("/api/security/ssh", get(handlers::network_security::list_ssh))

        // SOC Workflow (V5 Prompt 8)
        .route("/api/security/cases", get(handlers::soc::list_cases))
        .route("/api/security/cases", post(handlers::soc::create_case))
        .route("/api/security/cases/:id", get(handlers::soc::get_case))
        .route("/api/security/cases/:id", put(handlers::soc::update_case))
        .route("/api/security/cases/:id/events", post(handlers::soc::add_case_event))
        .route("/api/security/alerts/:id/escalate", post(handlers::soc::escalate_alert))
        .route("/api/security/hunt", get(handlers::soc::hunt_search))
        .route("/api/security/ioc", get(handlers::soc::list_ioc))
        .route("/api/security/ioc", post(handlers::soc::add_ioc))
        .route("/api/security/ioc/:id", delete(handlers::soc::delete_ioc))
        .route("/api/security/ioc/check", post(handlers::soc::check_ioc))
        .route("/api/security/threat-intel/:indicator", get(handlers::soc::threat_intel_lookup))

        // Firewall (V5 Prompt 9)
        .route("/api/security/firewall/logs", get(handlers::firewall::list_firewall_logs))
        .route("/api/security/firewall/rules", get(handlers::firewall::list_firewall_rules))
        .route("/api/security/firewall/stats", get(handlers::firewall::firewall_stats))
        .route("/api/security/firewall/ingest", post(handlers::firewall::ingest_firewall))

        // File Analysis (V5 Prompt 9)
        .route("/api/security/files", get(handlers::file_analysis::list_files))
        .route("/api/security/files/scan", post(handlers::file_analysis::scan_file))
        .route("/api/security/files/rules", get(handlers::file_analysis::list_yara_rules))
        .route("/api/security/files/rules", post(handlers::file_analysis::create_yara_rule))
        .route("/api/security/files/stats", get(handlers::file_analysis::file_stats))
        .route("/api/security/files/:id", get(handlers::file_analysis::get_file))

        // LLM Security (V5 Prompt 13)
        .route("/api/llm-security/overview", get(handlers::llm_security::overview))
        .route("/api/llm-security/scan", post(handlers::llm_security::scan_prompt))
        .route("/api/llm-security/events", get(handlers::llm_security::list_events))
        .route("/api/llm-security/events/:id", get(handlers::llm_security::get_event))
        .route("/api/llm-security/stats", get(handlers::llm_security::stats))
        .route("/api/llm-security/rules", get(handlers::llm_security::list_rules))
        .route("/api/llm-security/rules", post(handlers::llm_security::create_rule))
        .route("/api/llm-security/rules/:id", put(handlers::llm_security::update_rule))
        .route("/api/llm-security/models", get(handlers::llm_security::list_models))
        .route("/api/llm-security/ingest", post(handlers::llm_security::ingest))
}
