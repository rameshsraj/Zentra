use axum::{Router, routing::{get, post, put, delete}};
use crate::state::AppState;
use crate::handlers;

pub fn router() -> Router<AppState> {
    Router::new()
        // Health Checks (Icinga2-inspired)
        .route("/api/healthchecks", get(handlers::healthchecks::list_checks))
        .route("/api/healthchecks", post(handlers::healthchecks::create_check))
        .route("/api/healthchecks/summary", get(handlers::healthchecks::get_summary))
        .route("/api/healthchecks/matrix", get(handlers::healthchecks::get_matrix))
        .route("/api/healthchecks/groups", get(handlers::healthchecks::list_groups))
        .route("/api/healthchecks/uptime", get(handlers::healthchecks::get_uptime))
        .route("/api/healthchecks/bulk", post(handlers::healthchecks::bulk_create))
        .route("/api/healthchecks/:id", get(handlers::healthchecks::get_check))
        .route("/api/healthchecks/:id", put(handlers::healthchecks::update_check))
        .route("/api/healthchecks/:id", delete(handlers::healthchecks::delete_check))
        .route("/api/healthchecks/:id/run", post(handlers::healthchecks::run_check))
        .route("/api/healthchecks/:id/history", get(handlers::healthchecks::get_history))

        // Monitoring Templates (Zabbix-inspired)
        .route("/api/monitoring-templates", get(handlers::monitoring_templates::list_templates))
        .route("/api/monitoring-templates", post(handlers::monitoring_templates::create_template))
        .route("/api/monitoring-templates/assignments", get(handlers::monitoring_templates::list_assignments))
        .route("/api/monitoring-templates/categories", get(handlers::monitoring_templates::list_categories))
        .route("/api/monitoring-templates/import", post(handlers::monitoring_templates::import_template))
        .route("/api/monitoring-templates/import-bundle", post(handlers::monitoring_templates::import_bundle))
        .route("/api/monitoring-templates/:id", get(handlers::monitoring_templates::get_template))
        .route("/api/monitoring-templates/:id", put(handlers::monitoring_templates::update_template))
        .route("/api/monitoring-templates/:id", delete(handlers::monitoring_templates::delete_template))
        .route("/api/monitoring-templates/:id/export", get(handlers::monitoring_templates::export_template))
        .route("/api/monitoring-templates/:id/assign", post(handlers::monitoring_templates::assign_template))
        .route("/api/monitoring-templates/:id/unassign/:target_id", delete(handlers::monitoring_templates::unassign_template))

        // Maintenance Windows (P3)
        .route("/api/maintenance-windows", get(handlers::maintenance::list_windows))
        .route("/api/maintenance-windows", post(handlers::maintenance::create_window))
        .route("/api/maintenance-windows/active", get(handlers::maintenance::active_windows))
        .route("/api/maintenance-windows/check/:target_id", get(handlers::maintenance::check_target_maintenance))
        .route("/api/maintenance-windows/:id", put(handlers::maintenance::update_window))
        .route("/api/maintenance-windows/:id", delete(handlers::maintenance::delete_window))

        // SLA Reports (P3)
        .route("/api/sla/reports", get(handlers::maintenance::sla_reports))
        .route("/api/sla/reports/:check_id", get(handlers::maintenance::sla_report_detail))
        .route("/api/sla/targets", put(handlers::maintenance::set_sla_targets))
        .route("/api/sla/summary", get(handlers::maintenance::sla_summary))

        // Dependencies (P4)
        .route("/api/dependencies", get(handlers::dependencies::list_dependencies))
        .route("/api/dependencies", post(handlers::dependencies::create_dependency))
        .route("/api/dependencies/tree", get(handlers::dependencies::dependency_tree))
        .route("/api/dependencies/:id", delete(handlers::dependencies::delete_dependency))

        // Flapping Detection (P4)
        .route("/api/healthchecks/flapping", get(handlers::dependencies::list_flapping))
        .route("/api/healthchecks/:id/flapping/acknowledge", put(handlers::dependencies::acknowledge_flapping))

        // Deployments (P9)
        .route("/api/deployments", get(handlers::deployments::list_deployments))
        .route("/api/deployments", post(handlers::deployments::create_deployment))
        .route("/api/deployments/environments", get(handlers::deployments::list_environments))
        .route("/api/deployments/runbooks", get(handlers::deployments::list_runbooks))
        .route("/api/deployments/runbooks", post(handlers::deployments::create_runbook))
        .route("/api/deployments/runbooks/:id", put(handlers::deployments::update_runbook))
        .route("/api/deployments/runbooks/:id", delete(handlers::deployments::delete_runbook))
        .route("/api/deployments/:id", get(handlers::deployments::get_deployment))
        .route("/api/deployments/:id", put(handlers::deployments::update_deployment))
        .route("/api/deployments/:id", delete(handlers::deployments::delete_deployment))
        .route("/api/deployments/:id/pre-check", post(handlers::deployments::pre_check))
        .route("/api/deployments/:id/post-check", post(handlers::deployments::post_check))
        .route("/api/deployments/:id/rollback", post(handlers::deployments::rollback))
        .route("/api/deployments/:id/approve", post(handlers::deployments::approve))

        // Alert Dependencies
        .route("/api/alert-rules/:id/dependencies", get(handlers::alert_dependencies::list_dependencies))
        .route("/api/alert-rules/:id/dependencies", post(handlers::alert_dependencies::create_dependency))
        .route("/api/alert-rules/dependencies/:dep_id", delete(handlers::alert_dependencies::delete_dependency))
        .route("/api/alert-rules/dependency-graph", get(handlers::alert_dependencies::dependency_graph))
}
