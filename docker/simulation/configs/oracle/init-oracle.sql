-- Creates a monitoring user and sample schema for Zentra to discover.
-- =============================================================================

-- Create monitoring user for Zentra
CREATE USER zentra_mon IDENTIFIED BY zentra123
  DEFAULT TABLESPACE USERS
  TEMPORARY TABLESPACE TEMP
  QUOTA UNLIMITED ON USERS;

GRANT CREATE SESSION TO zentra_mon;
GRANT SELECT_CATALOG_ROLE TO zentra_mon;
GRANT SELECT ANY DICTIONARY TO zentra_mon;

-- Grant access to performance views
GRANT SELECT ON SYS.V_$SESSION TO zentra_mon;
GRANT SELECT ON SYS.V_$SYSSTAT TO zentra_mon;
GRANT SELECT ON SYS.V_$SYSTEM_EVENT TO zentra_mon;
GRANT SELECT ON SYS.V_$INSTANCE TO zentra_mon;
GRANT SELECT ON SYS.V_$DATABASE TO zentra_mon;
GRANT SELECT ON SYS.V_$TABLESPACE TO zentra_mon;
GRANT SELECT ON SYS.V_$LOG TO zentra_mon;
GRANT SELECT ON SYS.V_$ARCHIVE_DEST TO zentra_mon;
GRANT SELECT ON SYS.V_$OSSTAT TO zentra_mon;
GRANT SELECT ON SYS.V_$PGASTAT TO zentra_mon;
GRANT SELECT ON SYS.V_$SGASTAT TO zentra_mon;
GRANT SELECT ON SYS.DBA_TABLESPACES TO zentra_mon;
GRANT SELECT ON SYS.DBA_DATA_FILES TO zentra_mon;
GRANT SELECT ON SYS.DBA_FREE_SPACE TO zentra_mon;

-- Create a sample application schema
CREATE USER appuser IDENTIFIED BY appuser123
  DEFAULT TABLESPACE USERS
  TEMPORARY TABLESPACE TEMP
  QUOTA UNLIMITED ON USERS;

GRANT CREATE SESSION TO appuser;
GRANT CREATE TABLE TO appuser;
GRANT CREATE SEQUENCE TO appuser;

-- Sample tables to generate some activity
CREATE TABLE appuser.customers (
  id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name      VARCHAR2(100) NOT NULL,
  email     VARCHAR2(200),
  created   TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE appuser.orders (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id NUMBER REFERENCES appuser.customers(id),
  total       NUMBER(10,2),
  status      VARCHAR2(20) DEFAULT 'pending',
  created     TIMESTAMP DEFAULT SYSTIMESTAMP
);

